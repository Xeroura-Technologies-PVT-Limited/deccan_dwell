"""Generates an original palm-frond shadow as a resolution-independent SVG.

Coconut-palm style: fronds radiate from a crown just off the top-left corner;
each frond is a drooping rachis lined with long, tapering, slightly curved
leaflets. A crisp core layer sits over a softer, wider penumbra layer so it
reads as a real shadow cast on a wall.
"""
import math, random, sys

random.seed(11)
W, H = 1000, 1400
CROWN = (-70.0, -40.0)

# Every point we draw, so the viewBox can be fitted to the whole palm —
# no frond is ever sliced off by the edge of the SVG.
BOUNDS = [0.0, 0.0, 0.0, 0.0]  # min x, min y, max x, max y

def track(*pts):
    for x, y in pts:
        BOUNDS[0] = min(BOUNDS[0], x)
        BOUNDS[1] = min(BOUNDS[1], y)
        BOUNDS[2] = max(BOUNDS[2], x)
        BOUNDS[3] = max(BOUNDS[3], y)

def bez(p0, p1, p2, t):
    u = 1 - t
    return (u*u*p0[0] + 2*u*t*p1[0] + t*t*p2[0], u*u*p0[1] + 2*u*t*p1[1] + t*t*p2[1])

def bez_d(p0, p1, p2, t):
    return (2*(1-t)*(p1[0]-p0[0]) + 2*t*(p2[0]-p1[0]), 2*(1-t)*(p1[1]-p0[1]) + 2*t*(p2[1]-p1[1]))

def norm(v):
    l = math.hypot(*v) or 1
    return (v[0]/l, v[1]/l)

def rot(v, a):
    c, s = math.cos(a), math.sin(a)
    return (v[0]*c - v[1]*s, v[0]*s + v[1]*c)

def f(n):
    return f"{n:.1f}"

def leaflet(base, d, length, width, droop):
    """A tapering blade from `base` along unit direction `d`, bending by gravity."""
    d = norm(d)
    perp = (-d[1], d[0])
    tip = (base[0] + d[0]*length, base[1] + d[1]*length + droop*length)
    mid = (base[0] + d[0]*length*0.5, base[1] + d[1]*length*0.5 + droop*length*0.18)
    b1 = (base[0] + perp[0]*width*0.5, base[1] + perp[1]*width*0.5)
    b2 = (base[0] - perp[0]*width*0.5, base[1] - perp[1]*width*0.5)
    c1 = (mid[0] + perp[0]*width*0.55, mid[1] + perp[1]*width*0.55)
    c2 = (mid[0] - perp[0]*width*0.55, mid[1] - perp[1]*width*0.55)
    track(b1, b2, c1, c2, tip)
    return (f"M{f(b1[0])} {f(b1[1])}Q{f(c1[0])} {f(c1[1])} {f(tip[0])} {f(tip[1])}"
            f"Q{f(c2[0])} {f(c2[1])} {f(b2[0])} {f(b2[1])}Z")

def frond(angle_deg, length, arch, gravity, leaf_len, count, seed):
    rnd = random.Random(seed)
    a = math.radians(angle_deg)
    dirv = (math.cos(a), math.sin(a))
    perp = (dirv[1], -dirv[0])  # points "up" relative to the frond
    p0 = CROWN
    p2 = (p0[0] + dirv[0]*length, p0[1] + dirv[1]*length + gravity*length)
    p1 = (p0[0] + dirv[0]*length*0.5 + perp[0]*arch*length,
          p0[1] + dirv[1]*length*0.5 + perp[1]*arch*length)
    parts = []
    # rachis: a thin tapered stroke drawn as a filled sliver
    pts_l, pts_r = [], []
    for i in range(0, 41):
        t = i / 40
        p = bez(p0, p1, p2, t)
        tn = norm(bez_d(p0, p1, p2, t))
        w = 9 * (1 - t) + 1.2
        pts_l.append((p[0] - tn[1]*w/2, p[1] + tn[0]*w/2))
        pts_r.append((p[0] + tn[1]*w/2, p[1] - tn[0]*w/2))
    poly = pts_l + pts_r[::-1]
    track(*poly)
    parts.append("M" + "L".join(f"{f(x)} {f(y)}" for x, y in poly) + "Z")
    for side in (1, -1):
        for i in range(count):
            t = 0.07 + 0.92 * (i / (count - 1))
            if rnd.random() < 0.05:
                continue  # a missing leaflet now and then
            base = bez(p0, p1, p2, t)
            tn = norm(bez_d(p0, p1, p2, t))
            spread = math.radians(62 - 30 * t + rnd.uniform(-7, 7))
            d = rot(tn, side * spread)
            env = math.sin(math.pi * min(1.0, 0.12 + t * 0.98)) ** 0.7
            ln = leaf_len * (0.3 + 0.7 * env) * (1 - 0.45 * t) * rnd.uniform(0.86, 1.12)
            wd = (7.5 - 4.5 * t) * rnd.uniform(0.85, 1.15)
            droop = 0.22 + 0.25 * t + rnd.uniform(-0.05, 0.05)
            parts.append(leaflet(base, d, ln, wd, droop))
    return "".join(parts)

FRONDS = [
    # angle, length, arch, gravity, leaflet length, leaflets per side
    (-6, 1120, 0.10, 0.18, 210, 48),
    (14, 1240, 0.13, 0.22, 230, 52),
    (33, 1300, 0.12, 0.20, 240, 54),
    (52, 1260, 0.10, 0.16, 230, 52),
    (70, 1180, 0.08, 0.10, 215, 48),
    (88, 1040, 0.06, 0.06, 190, 44),
    (24, 760, 0.16, 0.30, 170, 36),
    (62, 820, 0.12, 0.18, 175, 38),
]

paths = [frond(*fr, seed=k) for k, fr in enumerate(FRONDS)]
d_all = "".join(paths)

# The crown sits off the top-left corner on purpose (the palm grows from
# off-screen); everything else — every leaflet tip — fits inside, with a
# margin for the blur.
PAD = 40
VW = int(BOUNDS[2] + PAD)
VH = int(BOUNDS[3] + PAD)
sys.stderr.write(f"viewBox 0 0 {VW} {VH} (width ratio {VW / W:.4f})\n")

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {VW} {VH}" width="{VW}" height="{VH}">
  <!-- Original palm-frond shadow for Deccan Dwell. Generated by scripts/palm-shadow.py -->
  <defs>
    <filter id="soft" x="-5%" y="-5%" width="110%" height="110%">
      <feGaussianBlur stdDeviation="7"/>
    </filter>
    <filter id="edge" x="-5%" y="-5%" width="110%" height="110%">
      <feGaussianBlur stdDeviation="1.6"/>
    </filter>
    <path id="p" d="{d_all}"/>
  </defs>
  <g fill="#03120f">
    <use href="#p" filter="url(#soft)" opacity="0.55"/>
    <use href="#p" filter="url(#edge)" opacity="0.95"/>
  </g>
</svg>
'''
sys.stdout.write(svg)
